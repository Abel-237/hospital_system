def escape_str(s):
    return s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')

def generate_po_file(entries, out_path, lang='en'):
    lines = [
        f'# Translation file for {lang}',
        'msgid ""',
        'msgstr ""',
        '"Project-Id-Version: hospital_system 2026.1\\n"',
        '"Report-Msgid-Bugs-To: \\n"',
        '"POT-Creation-Date: 2026-09-12 18:00+0100\\n"',
        '"PO-Revision-Date: 2026-09-12 18:00+0100\\n"',
        '"Last-Translator: Admin <admin@hospital-cmr.local>\\n"',
        f'"Language-Team: {lang}\\n"',
        f'"Language: {lang}\\n"',
        '"MIME-Version: 1.0\\n"',
        '"Content-Type: text/plain; charset=UTF-8\\n"',
        '"Content-Transfer-Encoding: 8bit\\n"',
        '"Plural-Forms: nplurals=2; plural=(n != 1);\\n"',
        '',
    ]

    for msgid, msgstr in sorted(entries.items(), key=lambda x: x[0]):
        if not msgid:
            continue
        lines.append(f'msgid "{escape_str(msgid)}"')
        lines.append(f'msgstr "{escape_str(msgstr)}"')
        lines.append('')

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text('\n'.join(lines), encoding='utf-8')
    print(f"[OK] Wrote {len(entries)} entries to {out_path}")

def build_all():
    # 1. Read existing en/django.po entries if any
    en_po = BASE_DIR / 'locale' / 'en' / 'LC_MESSAGES' / 'django.po'
    current_en = {}
    if en_po.exists():
        from compile_translations import parse_po
        current_en = parse_po(en_po.read_text(encoding='utf-8'))

    # 2. Merge with our comprehensive TRANSLATIONS dictionary
    merged_en = dict(current_en)
    for k, v in TRANSLATIONS.items():
        # Always prefer our rich translations or update missing
        merged_en[k] = v

    # 3. Also read all strings in templates/apps and ensure every single one has an entry
    audit_file = BASE_DIR / 'audit_i18n.py'
    if audit_file.exists():
        # Extract translatable strings dynamically
        trans_regex = re.compile(r'{%\s*trans\s+[\'"](.*?)[\'"]\s*%}')
        py_regex = re.compile(r'_\([\'"](.*?)[\'"]\)')
        for p in (BASE_DIR / 'templates').glob('**/*.html'):
            txt = p.read_text(encoding='utf-8')
            for m in trans_regex.finditer(txt):
                s = m.group(1).strip()
                if s and s not in merged_en:
                    # If not explicitly translated, map to a reasonable fallback
                    merged_en[s] = TRANSLATIONS.get(s, s)
        for p in (BASE_DIR / 'apps').glob('**/*.py'):
            txt = p.read_text(encoding='utf-8')
            for m in py_regex.finditer(txt):
                s = m.group(1).strip()
                if s and s not in merged_en:
                    merged_en[s] = TRANSLATIONS.get(s, s)

    # 4. Write English PO
    generate_po_file(merged_en, en_po, lang='en')

    # 5. Write French PO (French strings match source)
    fr_po = BASE_DIR / 'locale' / 'fr' / 'LC_MESSAGES' / 'django.po'
    fr_entries = {k: k for k in merged_en.keys()}
    generate_po_file(fr_entries, fr_po, lang='fr')

    # 6. Compile both to .mo
    from compile_translations import compile_all
    compile_all(BASE_DIR)

if __name__ == '__main__':
    build_all()
